// codes couleur ANSI, toujours finir avec Reset sinon tout le terminal reste coloré
const (
	Reset  = "\033[0m"
	Gras   = "\033[1m"
	Rouge  = "\033[31m"
	Vert   = "\033[32m"
	Jaune  = "\033[33m"
	Bleu   = "\033[34m"
	Violet = "\033[35m"
	Cyan   = "\033[36m"
)

// PrintLore affiche un texte lettre par lettre puis attend l'appui sur Entrée.
func PrintLore(text string, delayMs time.Duration) {
	fmt.Println()
	for _, char := range text {
		fmt.Printf("%c", char)
		time.Sleep(delayMs * time.Millisecond)
	}
	fmt.Print("\n")

	fmt.Print("--> Appuyez sur [ENTRÉE] pour continuer...")
	reader := bufio.NewReader(os.Stdin)
	reader.ReadString('\n')
	fmt.Println()
}

// affiche le message et lit une ligne, renvoie le texte sans espaces autour
func LireEntree(message string) string {
	scanner := bufio.NewScanner(os.Stdin)
	fmt.Print(message)
	if scanner.Scan() {
		return strings.TrimSpace(scanner.Text())
	}
	return ""
}

// séquence ANSI : curseur en haut à gauche puis on efface l'écran
func ClearConsole() {
	fmt.Print("\033[H\033[2J")
}

// bandeau de titre en majuscules
func AfficherTitre(titre string) {
	fmt.Println(Cyan + "==================================================" + Reset)
	fmt.Println(Gras + Cyan + "   " + strings.ToUpper(titre) + Reset)
	fmt.Println(Cyan + "==================================================" + Reset)
}

