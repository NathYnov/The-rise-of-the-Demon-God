func AfficherFichePersonnage(
	nom, race string, niveau, ngPlus int,
	pv, maxPV, mana, maxMana int,
	xp, maxXP, or int,
	attaque, buffAttaque int,
	defense, buffDefense int,
	dexterite int,
	equipTete, equipTorse, equipArme string,
	nbInventaire, maxInventaire int,
) {
	ClearConsole()
	AfficherTitre(fmt.Sprintf("Fiche de Personnage - %s (%s)", nom, race))

	// Gestion des valeurs d'équipement par défaut si vides
	if equipTete == "" {
		equipTete = "Aucun"
	}
	if equipTorse == "" {
		equipTorse = "Aucun"
	}
	if equipArme == "" {
		equipArme = "Mains nues"
	}

	// Mode de jeu / NG+
	modeStr := "Normal"
	if ngPlus > 0 {
		modeStr = fmt.Sprintf("NG+%d", ngPlus)
	}

	// Barres de statut visuelles
	barrePV := GenererBarre(pv, maxPV, 15, Rouge)
	barreMana := GenererBarre(mana, maxMana, 15, Bleu)
	barreXP := GenererBarre(xp, maxXP, 15, Violet)

	// Affichage général
	fmt.Printf(" Mode de jeu : %s%s%s\n", Jaune, modeStr, Reset)
	fmt.Printf(" Niveau      : %d | XP : [%s] %d/%d\n\n", niveau, barreXP, xp, maxXP)

	// Santé & Mana
	fmt.Printf(" %sPV%s   : [%s] %d/%d\n", Rouge, Reset, barrePV, pv, maxPV)
	fmt.Printf(" %sMana%s : [%s] %d/%d\n\n", Bleu, Reset, barreMana, mana, maxMana)

	// Statistiques de combat
	fmt.Println("--- Statistiques ---")
	fmt.Printf(" Attaque   : %d ", attaque)
	if buffAttaque > 0 {
		fmt.Printf("(%s+%d buff%s)", Vert, buffAttaque, Reset)
	}
	fmt.Println()

	fmt.Printf(" Défense   : %d ", defense)
	if buffDefense > 0 {
		fmt.Printf("(%s+%d buff%s)", Vert, buffDefense, Reset)
	}
	fmt.Println()

	fmt.Printf(" Dextérité : %d\n\n", dexterite)

	// Équipement & Inventaire
	fmt.Println("--- Équipement ---")
	fmt.Printf(" Tête  : %s\n", equipTete)
	fmt.Printf(" Torse : %s\n", equipTorse)
	fmt.Printf(" Arme  : %s\n\n", equipArme)

	// Économie & Sac
	fmt.Println("--- Richesse & Sac ---")
	fmt.Printf(" Or         : %s%d PO%s\n", Jaune, or, Reset)
	fmt.Printf(" Inventaire : %d/%d objets\n", nbInventaire, maxInventaire)
}

