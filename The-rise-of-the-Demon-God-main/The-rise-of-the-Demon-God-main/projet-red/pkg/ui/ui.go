// FormatASCIIArt tronque ou complète chaque ligne pour garantir une largeur fixe
func FormatASCIIArt(art string, maxWidth int, maxHeight int) []string {
	lines := strings.Split(art, "\n")
	var formatted []string

	for i, line := range lines {
		if i >= maxHeight {
			break // Limite la hauteur
		}
		// Limite la largeur de la ligne
		if len(line) > maxWidth {
			line = line[:maxWidth]
		} else {
			// Complète avec des espaces si besoin de remplir
			line = line + strings.Repeat(" ", maxWidth-len(line))
		}
		formatted = append(formatted, line)
	}

	// Complète avec des lignes vides si l'ASCII art est plus court que maxHeight
	for len(formatted) < maxHeight {
		formatted = append(formatted, strings.Repeat(" ", maxWidth))
	}

	return formatted
}
