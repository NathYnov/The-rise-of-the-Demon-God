// Génère une barre visuelle [█████░░░░░]
func GenererBarre(actuel, max int, taille int, couleur string) string {
	if max <= 0 {
		max = 1
	}
	ratio := float64(actuel) / float64(max)
	if ratio < 0 {
		ratio = 0
	}
	if ratio > 1 {
		ratio = 1
	}

	remplis := int(ratio * float64(taille))
	vides := taille - remplis

	barre := couleur + strings.Repeat("█", remplis) + Vert + strings.Repeat("░", vides) + Reset
	return fmt.Sprintf("[%s] %d/%d", barre, actuel, max)
}

// Affiche les stats d'une entité (Joueur ou Monstre)
func AfficherStatutCombat(nom string, pvActuel, pvMax, pmActuel, pmMax int, etats []string) {
	fmt.Println(Gras + nom + Reset)
	fmt.Printf("  PV:   %s\n", GenererBarre(pvActuel, pvMax, 15, Vert))
	if pmMax > 0 {
		fmt.Printf("  PM:   %s\n", GenererBarre(pmActuel, pmMax, 15, Bleu))
	}
	if len(etats) > 0 {
		fmt.Printf("  État: %s%s%s\n", Violet, strings.Join(etats, ", "), Reset)
	} else {
		fmt.Printf("  État: %sAucun%s\n", Vert, Reset)
	}
	fmt.Println(Vert + "--------------------------------------------------" + Reset)
}

// Interface d'action de combat (redessine proprement l'écran sans garder l'historique texte)
func RedessinerCombat(nomJoueur string, pvJ, pvMaxJ, pmJ, pmMaxJ int, etatsJ []string,
	nomMonstre string, pvM, pvMaxM int, etatsM []string, dernierMessage string) {

	ClearConsole()
	AfficherTitre("COMBAT EN COURS")

	// Art du monstre
	DisplayMonsterArt(nomMonstre)

	// Statuts
	AfficherStatutCombat(nomMonstre, pvM, pvMaxM, 0, 0, etatsM)
	AfficherStatutCombat(nomJoueur, pvJ, pvMaxJ, pmJ, pmMaxJ, etatsJ)

	// Affichage du dernier message d'action s'il y en a un
	if dernierMessage != "" {
		fmt.Println(Jaune + ">> " + dernierMessage + Reset)
		fmt.Println(Vert + "--------------------------------------------------" + Reset)
	}
}

